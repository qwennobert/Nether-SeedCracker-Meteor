public class NetherSeedCracker extends Module {
    /** Each surface must reveal this many bits before the crack starts on its own. */
    private static final double MIN_SURFACE_BITS = 32;
    /** Both surfaces together must reveal this many bits (48 for the seed plus margin). */
    private static final double MIN_TOTAL_BITS = 72;
    private static final int CHUNKS_PER_TICK = 4;
    private static final int CORES = Runtime.getRuntime().availableProcessors();

    private final SettingGroup sgGeneral = settings.getDefaultGroup();
    private final SettingGroup sgCracker = settings.createGroup("Cracker");
    private final SettingGroup sgOutput = settings.createGroup("Output");
    private final SettingGroup sgRender = settings.createGroup("Render");

    // General

    private final Setting<Boolean> autoStart = sgGeneral.add(new BoolSetting.Builder()
        .name("auto-start")
        .description("Start cracking on its own as soon as enough bedrock is collected. Otherwise use the Start button or .nsc start.")
        .defaultValue(true)
        .build()
    );

    private final Setting<Integer> scanRadius = sgGeneral.add(new IntSetting.Builder()
        .name("scan-radius")
        .description("Loaded chunks within this many chunks around you are read. One chunk is already plenty of data.")
        .defaultValue(2)
        .range(0, 16)
        .sliderRange(0, 8)
        .build()
    );

    private final Setting<Integer> maxBlocks = sgGeneral.add(new IntSetting.Builder()
        .name("max-blocks")
        .description("How many blocks of each surface (floor and roof) the cracker uses. The most informative ones are picked.")
        .defaultValue(64)
        .range(16, 256)
        .sliderRange(16, 128)
        .onChanged(v -> selectionDirty = true)
        .build()
    );

    // Cracker

    private final Setting<Integer> threads = sgCracker.add(new IntSetting.Builder()
        .name("threads")
        .description("CPU threads for cracking. More is faster, but the game may lag.")
        .defaultValue(Math.max(1, CORES / 2))
        .range(1, CORES)
        .sliderRange(1, CORES)
        .build()
    );

    private final Setting<BedrockGeneration> generation = sgCracker.add(new EnumSetting.Builder<BedrockGeneration>()
        .name("generation")
        .description("Vanilla for almost every server. PaperOld if the nether was generated by PaperMC before 1.19.2 build 213 (bedrock looks like pillars).")
        .defaultValue(BedrockGeneration.Vanilla)
        .build()
    );

    private final Setting<Boolean> useHashedSeed = sgCracker.add(new BoolSetting.Builder()
        .name("use-hashed-seed")
        .description("Use the hashed seed the server sends on join to find the full 64 bit world seed. Also works for seeds the admin typed in.")
        .defaultValue(true)
        .build()
    );

    private final Setting<Boolean> stopWhenFound = sgCracker.add(new BoolSetting.Builder()
        .name("stop-when-found")
        .description("Stop as soon as a seed matches the hashed seed of the server, instead of searching all seeds.")
        .defaultValue(true)
        .visible(useHashedSeed::get)
        .build()
    );

    // Output

    private final Setting<Boolean> saveToFile = sgOutput.add(new BoolSetting.Builder()
        .name("save-to-file")
        .description("Append found seeds to .minecraft/meteor-client/nether-seedcracker/seeds.txt.")
        .defaultValue(true)
        .build()
    );

    private final Setting<Boolean> sendToSeedMapper = sgOutput.add(new BoolSetting.Builder()
        .name("send-to-seedmapper")
        .description("Save the world seed for this server in SeedMapper (/sm:config SavedSeeds add <seed>), if SeedMapper is installed.")
        .defaultValue(false)
        .build()
    );

    private final Setting<Boolean> sendToSeedMiner = sgOutput.add(new BoolSetting.Builder()
        .name("send-to-seed-miner")
        .description("Set the world seed as manual seed of the Seed Miner addon (.seedminer seed <seed>), if it is installed.")
        .defaultValue(true)
        .build()
    );

    // Render

    private final Setting<Boolean> render = sgRender.add(new BoolSetting.Builder()
        .name("render")
        .description("Highlight the blocks used for cracking.")
        .defaultValue(false)
        .build()
    );

    private final Setting<ShapeMode> shapeMode = sgRender.add(new EnumSetting.Builder<ShapeMode>()
        .name("shape-mode")
        .description("How the blocks are rendered.")
        .defaultValue(ShapeMode.Lines)
        .visible(render::get)
        .build()
    );

    private final Setting<SettingColor> bedrockColor = sgRender.add(new ColorSetting.Builder()
        .name("bedrock-color")
        .description("Color of used bedrock blocks.")
        .defaultValue(new SettingColor(0, 255, 120, 120))
        .visible(render::get)
        .build()
    );

    private final Setting<SettingColor> otherColor = sgRender.add(new ColorSetting.Builder()
        .name("other-color")
        .description("Color of used non-bedrock blocks.")
        .defaultValue(new SettingColor(255, 80, 40, 120))
        .visible(render::get)
        .build()
    );

    public enum State {
        Idle,
        WaitingForNether,
        Collecting,
        Cracking,
        Done,
        Failed
    }

    private final BedrockCollector collector = new BedrockCollector();
    private List<BedrockBlock> selected = List.of();
    private double floorBits, roofBits;
    private boolean selectionDirty;
    private int selectTimer;
    /** Server and hashed seed the collected data belongs to. */
    private String worldId;

    private BedrockCracker.Search search;
    /** Filled by the worker threads of the current search, every search gets its own queue. */
    private Queue<SeedCandidate> found = new ConcurrentLinkedQueue<>();
    private List<BedrockBlock> usedBlocks = List.of();
    private Long hashedSeed;
    private final List<SeedCandidate> candidates = new ArrayList<>();
    /** Stopped with the Stop button or command, don't start again on its own. */
    private boolean stoppedByUser;

    private Long worldSeed;
    private boolean worldSeedVerified;
    private State state = State.Idle;
    private String status = "Idle";

    public NetherSeedCracker() {
        super(NetherCrackerAddon.CATEGORY, "nether-seed-cracker", "Collects nether bedrock and cracks the world seed from it.");
    }

    @Override
    public void onActivate() {
        if (state == State.Done && worldSeed != null) {
            info(Text.literal("World seed already found: ").append(SeedOutput.seedText(worldSeed)).append(". Use .nsc reset to crack again."));
            return;
        }
        if (state == State.Idle || state == State.Failed) setState(State.Collecting, "Collecting bedrock");
    }

    @Override
    public void onDeactivate() {
        if (state == State.Cracking) {
            cancelSearch();
            setState(State.Idle, "Idle");
            info("Cracking stopped.");
        }
        else if (state != State.Done && state != State.Failed) {
            setState(State.Idle, "Idle");
        }
    }

    @EventHandler
    private void onGameLeft(GameLeftEvent event) {
        reset();
        if (isActive()) setState(State.Collecting, "Collecting bedrock");
    }

    @EventHandler
    private void onTick(TickEvent.Post event) {
        if (mc.world == null || mc.player == null) return;

        // Data from another server or world is useless
        String id = currentWorldId();
        if (worldId != null && !worldId.equals(id)) {
            reset();
            setState(State.Collecting, "Collecting bedrock");
        }
        worldId = id;

        if (state == State.Cracking) {
            drainResults();
            if (state != State.Cracking) return;
            if (search == null || search.isFinished()) {
                finishSearch();
                return;
            }
            status = progressText();
            return;
        }
        if (state == State.Done || state == State.Failed) return;

        if (mc.world.getRegistryKey() != World.NETHER) {
            setState(State.WaitingForNether, "Go to the Nether");
            return;
        }

        int scanned = collector.scan(mc.world, mc.player.getChunkPos(), scanRadius.get(), CHUNKS_PER_TICK);
        if (scanned > 0 || selectionDirty || ++selectTimer >= 20) updateSelection();

        setState(State.Collecting, String.format("Collecting bedrock: floor %.0f, roof %.0f bits", floorBits, roofBits));
        if (autoStart.get() && !stoppedByUser && hasEnoughData()) start(false);
    }

    private void updateSelection() {
        selectTimer = 0;
        selectionDirty = false;
        selected = BlockSelector.select(collector.blocks(), maxBlocks.get());
        floorBits = BlockSelector.bits(selected, Surface.FLOOR);
        roofBits = BlockSelector.bits(selected, Surface.ROOF);
    }

    private boolean hasEnoughData() {
        return floorBits >= MIN_SURFACE_BITS && roofBits >= MIN_SURFACE_BITS && floorBits + roofBits >= MIN_TOTAL_BITS;
    }

    // Cracking

    /**
     * Starts cracking with the collected blocks.
     *
     * @param forced started by the user, also with little data
     */
    public void start(boolean forced) {
        if (mc.world == null) return;
        if (state == State.Cracking) {
            if (forced) warning("Already cracking.");
            return;
        }

        if (forced) stoppedByUser = false;
        updateSelection();
        if (selected.isEmpty()) {
            error("No bedrock collected yet. Go to the Nether and wait until chunks are loaded.");
            return;
        }
        if (!hasEnoughData()) {
            warning("Little data (floor %.0f, roof %.0f bits), expect many results. Collect data from floor and roof.", floorBits, roofBits);
        }

        BedrockCracker cracker = new BedrockCracker(selected, generation.get());
        hashedSeed = useHashedSeed.get() ? readHashedSeed() : null;
        usedBlocks = selected;
        candidates.clear();
        worldSeed = null;

        final Long hashed = hashedSeed;
        final Queue<SeedCandidate> queue = found = new ConcurrentLinkedQueue<>();
        search = cracker.start(threads.get(), structureSeed -> queue.add(SeedCandidate.resolve(structureSeed, hashed)), () -> {});

        info("Cracking with %d floor and %d roof blocks on %d threads%s.",
            countSurface(selected, Surface.FLOOR), countSurface(selected, Surface.ROOF), threads.get(),
            hashed == null ? "" : ", the hashed seed of the server finishes the world seed");
        NetherCrackerAddon.LOG.info("Cracking nether seed: primary {} ({} blocks, {} bits), secondary {} blocks ({} bits), hashed seed {}",
            cracker.primary(), cracker.primaryBlocks(), cracker.primaryBits(), cracker.secondaryBlocks(), cracker.secondaryBits(), hashed);
        setState(State.Cracking, "Cracking");
    }

    /** Stops cracking, the collected data is kept. */
    public void stop() {
        if (state != State.Cracking) return;
        cancelSearch();
        stoppedByUser = true;
        setState(isActive() ? State.Collecting : State.Idle, "Stopped");
        info("Cracking stopped. Start again with the Start button or .nsc start.");
    }

    /** Forgets the collected data and the result. */
    public void reset() {
        cancelSearch();
        collector.clear();
        selected = List.of();
        usedBlocks = List.of();
        floorBits = roofBits = 0;
        candidates.clear();
        found = new ConcurrentLinkedQueue<>();
        worldSeed = null;
        worldSeedVerified = false;
        hashedSeed = null;
        worldId = null;
        stoppedByUser = false;
        setState(isActive() ? State.Collecting : State.Idle, isActive() ? "Collecting bedrock" : "Idle");
    }

    private void cancelSearch() {
        if (search != null) search.cancel();
        search = null;
    }

    private void drainResults() {
        for (SeedCandidate candidate; (candidate = found.poll()) != null; ) {
            candidates.add(candidate);
            NetherCrackerAddon.LOG.info("Structure seed {} (verified world seed: {})", candidate.structureSeed(), candidate.verifiedSeed());

            if (candidate.verified() && worldSeed == null) {
                if (stopWhenFound.get()) cancelSearch();
                onWorldSeed(candidate.verifiedSeed().getAsLong(), true, candidate.structureSeed());
            }
            else if (hashedSeed == null) {
                info(Text.literal("Structure seed found: ").append(SeedOutput.seedText(candidate.structureSeed())).append(", still searching..."));
            }
        }
    }

    private void finishSearch() {
        drainResults();
        long seconds = search == null ? 0 : search.secondsElapsed();
        search = null;
        if (state != State.Cracking) return;

        if (worldSeed != null) {
            setState(State.Done, "Done: " + worldSeed);
            return;
        }

        if (candidates.isEmpty()) {
            setState(State.Failed, "No seed found");
            error("No seed matches the bedrock (searched in %ds). Possible reasons: the nether was generated before 1.18, "
                + "it was generated by PaperMC before 1.19.2 (try generation = PaperOld) or bedrock was changed. "
                + "Use .nsc reset and collect bedrock somewhere else.", seconds);
            return;
        }

        if (hashedSeed != null) {
            warning("No structure seed matches the hashed seed of the server, it may send a fake one. Showing all candidates.");
        }

        Set<Long> worldSeeds = new LinkedHashSet<>();
        for (SeedCandidate candidate : candidates) {
            info(SeedOutput.describe(candidate));
            for (long seed : candidate.randomWorldSeeds()) worldSeeds.add(seed);
            candidate.intWorldSeed().ifPresent(worldSeeds::add);
        }
        if (saveToFile.get()) SeedOutput.saveCandidates(serverName(), candidates);

        if (worldSeeds.size() == 1) {
            onWorldSeed(worldSeeds.iterator().next(), false, candidates.get(0).structureSeed());
        }
        else {
            setState(State.Done, candidates.size() + " structure seeds");
            info("Found %d structure seeds and %d possible world seeds. The structure seed is enough for structures and ores, "
                + "the full world seed also needs biomes (e.g. SeedcrackerX in the overworld).", candidates.size(), worldSeeds.size());
        }
    }

    private void onWorldSeed(long seed, boolean verified, long structureSeed) {
        worldSeed = seed;
        worldSeedVerified = verified;
        // Without stop-when-found the search goes on, finishSearch() ends it
        if (search == null) setState(State.Done, "Done: " + seed);

        MutableText message = Text.literal("World seed: ").append(SeedOutput.seedText(seed));
        message.append(verified ? " (matches the hashed seed of the server)" : " (not verified, the server's hashed seed was not used)");
        info(message);

        if (saveToFile.get()) SeedOutput.saveWorldSeed(serverName(), seed, verified, structureSeed);
        if (sendToSeedMapper.get()) SeedOutput.sendToSeedMapper(this, seed);
        if (sendToSeedMiner.get()) SeedOutput.sendToSeedMiner(this, seed);
    }

    // Helpers

    private Long readHashedSeed() {
        long seed = ((BiomeAccessAccessor) mc.world.getBiomeAccess()).nethercracker$getHashedSeed();
        // Servers that hide the seed usually send 0
        return seed == 0 ? null : seed;
    }

    private String currentWorldId() {
        long hashed = ((BiomeAccessAccessor) mc.world.getBiomeAccess()).nethercracker$getHashedSeed();
        return serverName() + "/" + hashed;
    }

    private String serverName() {
        if (mc.isInSingleplayer()) return "singleplayer";
        return mc.getCurrentServerEntry() != null ? mc.getCurrentServerEntry().address : "unknown";
    }

    private static int countSurface(List<BedrockBlock> blocks, Surface surface) {
        int count = 0;
        for (BedrockBlock block : blocks) if (Surface.at(block.y()) == surface) count++;
        return count;
    }

    private String progressText() {
        if (search == null) return "Cracking";
        long left = search.secondsLeft();
        return String.format("Cracking %.1f%%, %s left", search.progress() * 100, left < 0 ? "?" : SeedOutput.formatTime(left));
    }

    private void setState(State state, String status) {
        this.state = state;
        this.status = status;
    }

    @EventHandler
    private void onRender(Render3DEvent event) {
        if (!render.get() || mc.world == null || mc.world.getRegistryKey() != World.NETHER) return;

        List<BedrockBlock> blocks = state == State.Collecting ? selected : usedBlocks;
        for (BedrockBlock block : blocks) {
            SettingColor color = block.bedrock() ? bedrockColor.get() : otherColor.get();
            event.renderer.box(new BlockPos(block.x(), block.y(), block.z()), color, color, shapeMode.get(), 0);
        }
    }

    // GUI

    @Override
    public WWidget getWidget(GuiTheme theme) {
        WVerticalList list = theme.verticalList();

        list.add(theme.label("Status: " + status()));
        list.add(theme.label(String.format("Data: %d blocks from %d chunks, floor %.0f / roof %.0f bits", collector.size(), collector.scannedChunks(), floorBits, roofBits)));
        if (worldSeed != null) list.add(theme.label("World seed: " + worldSeed + (worldSeedVerified ? " (verified)" : " (not verified)")));
        else if (!candidates.isEmpty()) list.add(theme.label("Structure seeds: " + candidates.size()));

        WHorizontalList buttons = list.add(theme.horizontalList()).widget();

        WButton start = buttons.add(theme.button("Start")).widget();
        start.action = () -> start(true);

        WButton stop = buttons.add(theme.button("Stop")).widget();
        stop.action = this::stop;

        WButton reset = buttons.add(theme.button("Reset")).widget();
        reset.action = this::reset;

        if (worldSeed != null) {
            WButton copy = buttons.add(theme.button("Copy seed")).widget();
            copy.action = () -> mc.keyboard.setClipboard(Long.toString(worldSeed));
        }

        return list;
    }

    // API for the command and HUD

    public String status() {
        return !isActive() && state == State.Idle ? "Disabled" : status;
    }

    public State state() {
        return state;
    }

    /** Progress of the running search from 0 to 1, or -1. */
    public double progress() {
        return search == null ? -1 : search.progress();
    }

    public Long worldSeed() {
        return worldSeed;
    }

    public boolean worldSeedVerified() {
        return worldSeedVerified;
    }

    public List<SeedCandidate> candidates() {
        return candidates;
    }

    public double floorBits() {
        return floorBits;
    }

    public double roofBits() {
        return roofBits;
    }

    public BedrockCollector collector() {
        return collector;
    }

    public String server() {
        return mc.world == null ? "unknown" : serverName();
    }

    @Override
    public String getInfoString() {
        if (state == State.Cracking && search != null) return String.format("%.0f%%", search.progress() * 100);
        if (state == State.Done) return "done";
        return null;
    }
}
