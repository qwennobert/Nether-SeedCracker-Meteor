package com.qwennobert.nethercracker.collect;

import com.qwennobert.nethercracker.cracker.BedrockBlock;
import com.qwennobert.nethercracker.cracker.Surface;
import net.minecraft.block.BlockState;
import net.minecraft.block.Blocks;
import net.minecraft.client.world.ClientWorld;
import net.minecraft.util.math.BlockPos;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.world.chunk.ChunkStatus;
import net.minecraft.world.chunk.WorldChunk;

import java.util.Collection;
import java.util.Collections;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;

/**
 * Reads the random bedrock layers (y 1-4 and 123-126) of the loaded nether chunks.
 * <p>
 * Bedrock can't be broken or placed in survival, so "bedrock" and "not bedrock" stay what the world generated. Only
 * blocks that a generated nether portal may have put there are skipped.
 */
public class BedrockCollector {
    private final Map<Long, BedrockBlock> blocks = new LinkedHashMap<>();
    private final Set<Long> scannedChunks = new HashSet<>();

    /**
     * Scans loaded chunks within {@code radius} of {@code center} that were not scanned yet, nearest first.
     *
     * @return the number of chunks scanned
     */
    public int scan(ClientWorld world, ChunkPos center, int radius, int maxChunks) {
        int scanned = 0;
        for (int ring = 0; ring <= radius && scanned < maxChunks; ring++) {
            for (int dx = -ring; dx <= ring && scanned < maxChunks; dx++) {
                for (int dz = -ring; dz <= ring && scanned < maxChunks; dz++) {
                    if (Math.max(Math.abs(dx), Math.abs(dz)) != ring) continue;

                    int x = center.x + dx, z = center.z + dz;
                    if (scannedChunks.contains(ChunkPos.toLong(x, z))) continue;

                    if (world.getChunkManager().getChunk(x, z, ChunkStatus.FULL, false) instanceof WorldChunk chunk) {
                        scanChunk(chunk);
                        scannedChunks.add(ChunkPos.toLong(x, z));
                        scanned++;
                    }
                }
            }
        }
        return scanned;
    }

    private void scanChunk(WorldChunk chunk) {
        BlockPos.Mutable pos = new BlockPos.Mutable();
        int startX = chunk.getPos().getStartX(), startZ = chunk.getPos().getStartZ();

        for (Surface surface : Surface.values()) {
            for (int y = surface.minY; y <= surface.maxY; y++) {
                for (int dx = 0; dx < 16; dx++) {
                    for (int dz = 0; dz < 16; dz++) {
                        pos.set(startX + dx, y, startZ + dz);
                        BlockState state = chunk.getBlockState(pos);
                        if (isUnreliable(state)) continue;

                        blocks.put(pos.asLong(), new BedrockBlock(pos.getX(), y, pos.getZ(), state.isOf(Blocks.BEDROCK)));
                    }
                }
            }
        }
    }

    /** Portal frames generated by the game could replace bedrock. */
    private static boolean isUnreliable(BlockState state) {
        return state.isOf(Blocks.OBSIDIAN) || state.isOf(Blocks.CRYING_OBSIDIAN) || state.isOf(Blocks.NETHER_PORTAL);
    }

    public Collection<BedrockBlock> blocks() {
        return Collections.unmodifiableCollection(blocks.values());
    }

    public int size() {
        return blocks.size();
    }

    public int scannedChunks() {
        return scannedChunks.size();
    }

    public void clear() {
        blocks.clear();
        scannedChunks.clear();
    }
}
